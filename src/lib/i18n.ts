/** Urdu / Arabic script range used to distinguish scripts. */
const ARABIC_SCRIPT = /[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]/;

/** Words that appear in Punjabi (Shahmukhi) far more often than in Urdu. */
