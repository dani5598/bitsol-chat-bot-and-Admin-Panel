/**
 * =============================================================================
 *  Multilingual support — English · Urdu · Roman Urdu · Punjabi
 * =============================================================================
 *
 *  Two responsibilities:
 *
 *   1. `detectLanguage()` — a dependency-free heuristic that classifies a user
 *      message so the AI layer can be told which language to mirror and so the
 *      UI can switch text direction. It deliberately errs towards English when
 *      confidence is low; the model itself does the final, nuanced matching.
 *
 *   2. `t()` — a tiny dictionary for the handful of UI strings that must be
 *      localised outside the model (welcome menu, buttons, form labels). Full
 *      page copy stays in English; conversational content is generated by the
 *      model in the user's language.
 *
 *  Isomorphic — safe to import from client components.
 * =============================================================================
 */

